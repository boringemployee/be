// bannerRows renders text in the block font, one string per row. Glyphs are
// separated by one column. Unknown characters are skipped; validation in
// package profile only allows characters the font has.
func bannerRows(text string) [fontRows]string {
	var rows [fontRows]strings.Builder
	first := true
	for _, ch := range text {
		g, ok := font[ch]
		if !ok {
			continue
		}
		for i := range fontRows {
			if !first {
				rows[i].WriteByte(' ')
			}
			rows[i].WriteString(strings.ReplaceAll(g[i], "#", "█"))
		}
		first = false
	}
	var out [fontRows]string
	for i := range rows {
		out[i] = rows[i].String()
	}
	return out
}
